# Builds src/camera.c, the guest code of the replay god's eye view, into core/gdxsv/gdxsv_camera_blob.inc. A blob of its own: the
# payload that build.sh makes stays as released. Needs sh4-linux-gnu-gcc and python3, as build.sh does.
set -eu

SCRIPT_DIR=$(cd "$(dirname "$0")"; pwd)
cd "$SCRIPT_DIR"

rm -rf bin_camera
mkdir bin_camera

sh4-linux-gnu-gcc -O2 -fno-pic -fno-pie -fno-stack-protector -ffreestanding -fno-builtin \
	-fno-tree-loop-distribute-patterns -Wall -c src/camera.c -o bin_camera/camera.x
sh4-linux-gnu-ld -T src/camera.ld bin_camera/camera.x -o bin_camera/camera.o
sh4-linux-gnu-nm bin_camera/camera.o > bin_camera/symbols.txt
sh4-linux-gnu-size -A bin_camera/camera.o
sh4-linux-gnu-objcopy -O binary --only-section gdx.cam.func bin_camera/camera.o bin_camera/func.bin
sh4-linux-gnu-objcopy -O binary --only-section gdx.cam.data bin_camera/camera.o bin_camera/data.bin

python3 - <<'PY'
import hashlib
sym = {}
for line in open("bin_camera/symbols.txt"):
    p = line.split()
    if len(p) == 3:
        sym[p[2]] = int(p[0], 16)
code = open("bin_camera/func.bin", "rb").read()
data_size = len(open("bin_camera/data.bin", "rb").read())
if len(code) % 2:
    code += b"\0"
patch_id = int.from_bytes(hashlib.sha256(code).digest()[:4], "little") | 1
words = [code[i] | code[i + 1] << 8 for i in range(0, len(code), 2)]
with open("../core/gdxsv/gdxsv_camera_blob.inc", "w") as f:
    f.write("// Generated by gdxsv_patch/build_camera.sh from src/camera.c. Do not edit.\n")
    f.write(f"constexpr u32 kCamData = 0x{sym['gdx_cam']:08x}u;\n")
    f.write(f"constexpr u32 kCamTop = 0x{sym['gdx_top']:08x}u;\n")
    f.write(f"constexpr u32 kCamDataSize = {data_size}u;\n")
    f.write(f"constexpr u32 kCamControl = 0x{sym['gdx_cam_control']:08x}u;\n")
    f.write(f"constexpr u32 kCamPreRender = 0x{sym['gdx_cam_pre_render']:08x}u;\n")
    f.write(f"constexpr u32 kCamPostRender = 0x{sym['gdx_cam_post_render']:08x}u;\n")
    f.write("constexpr u32 kCamCode = 0x0c4f4000u;\n")
    f.write(f"constexpr u32 kCamPatchId = 0x{patch_id:08x}u;\n")
    f.write("static const u16 kCamCodeWords[] = {\n")
    for i in range(0, len(words), 12):
        f.write("\t" + ", ".join(f"0x{w:04x}" for w in words[i:i + 12]) + ",\n")
    f.write("};\n")
print("code bytes", len(code), "data bytes", data_size)
PY
