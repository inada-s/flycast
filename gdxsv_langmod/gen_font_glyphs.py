# Generate core/gdxsv/gdxsv_font_glyphs.inc: texture hash -> character of every DC2 font glyph.
# Usage: gen_font_glyphs.py <16 MB main RAM dump of DC2 in the lobby> <out .inc>
#
# The game's 24 px font is in RAM at 0x0c620010, 160 B per character (24x24, 2 bits per pixel, MSB first,
# 6 B per row), indexed by Shift-JIS (lead, trail) with 188 trails per lead. Half-width characters are at
# lead 0x85 (ASCII 0x21.. first, half-width kana after). A drawn character is a 32x32 ARGB1555 texture,
# glyph at the top-left, written with the level texels below; flycast's hash of it is
# XXH32(2048 B, seed 7) ^ 0x04000000.
import sys

BASE, STRIDE = 0x620010, 160
TEXEL = [0x0000, 0xB9CE, 0xDAD6, 0xFFFF]
P1, P2, P3, P4, P5 = 2654435761, 2246822519, 3266489917, 668265263, 374761393
M = 0xFFFFFFFF


def rotl(x, r):
    return ((x << r) | (x >> (32 - r))) & M


def xxh32(b, seed):
    n = len(b)
    i = 0
    v = [(seed + P1 + P2) & M, (seed + P2) & M, seed & M, (seed - P1) & M]
    while i + 16 <= n:
        for k in range(4):
            w = int.from_bytes(b[i:i + 4], 'little')
            i += 4
            v[k] = (rotl((v[k] + w * P2) & M, 13) * P1) & M
    h = (rotl(v[0], 1) + rotl(v[1], 7) + rotl(v[2], 12) + rotl(v[3], 18) + n) & M
    h ^= h >> 15
    h = (h * P2) & M
    h ^= h >> 13
    h = (h * P3) & M
    h ^= h >> 16
    return h


def code_char(lead, n):
    if lead == 0x85:
        if n < 94:
            return chr(0x21 + n)
        if n < 94 + 63:
            return bytes([0xA1 + n - 94]).decode('cp932')
        return None
    trail = 0x40 + n + (n >= 0x3F)
    try:
        return bytes([lead, trail]).decode('cp932')
    except UnicodeDecodeError:
        return None


def main():
    ram = open(sys.argv[1], 'rb').read()
    rows = {}
    for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xF0)):
        for n in range(188):
            if (lead, n) > (0xEA, 0xA4 - 0x41):
                break
            o = BASE + ((lead - 0x81 if lead < 0xA0 else lead - 0xC1) * 188 + n) * STRIDE
            g = ram[o:o + 144]
            if not any(g):
                continue
            lv = [[(g[y * 6 + x // 4] >> (6 - 2 * (x % 4))) & 3 for x in range(24)] for y in range(24)]
            px = bytearray(2048)
            for y in range(24):
                for x in range(24):
                    px[(y * 32 + x) * 2:(y * 32 + x) * 2 + 2] = TEXEL[lv[y][x]].to_bytes(2, 'little')
            h = xxh32(bytes(px), 7) ^ 0x04000000
            ch = code_char(lead, n)
            if h in rows or ch is None or not ch.isprintable():
                continue
            # Half-width glyphs keep the game's ink centre, full-width ones the centre of the 24 px box.
            xs = [x for y in range(24) for x in range(24) if lv[y][x]]
            centre2 = min(xs) + max(xs) + 1 if lead == 0x85 else 24
            rows[h] = (ord(ch), centre2, '%02x%02x' % (lead, 0x40 + n + (n >= 0x3F)))
    with open(sys.argv[2], 'w', newline='\n') as f:
        f.write('// Generated by gdxsv_langmod/gen_font_glyphs.py. Do not edit.\n')
        f.write('// { texture hash, Unicode code point, ink centre x in half game px }, sorted by hash.\n')
        for h in sorted(rows):
            cp, c2, sj = rows[h]
            f.write('{0x%08x, 0x%04x, %d}, // %s\n' % (h, cp, c2, sj))
    print(len(rows), 'glyphs')


if __name__ == '__main__':
    main()
